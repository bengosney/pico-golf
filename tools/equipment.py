"""Build a PicoSystem sprite sheet and art module from a folder of single frame PNGs.

Unlike tools/character.py the items can be different sizes, and they stay at
their original resolution. Each one is usable as an Actor's art.
"""

import argparse
from pathlib import Path

from character import CELL_SIZE, SHEET_WIDTH, write_pixels
from PIL import Image


def cells(pixels: int) -> int:
    return -(-pixels // CELL_SIZE)


def place_items(items: dict[str, Image.Image]) -> tuple[dict[str, tuple[int, int]], int]:
    """Lay items out in rows on the cell grid, returning their cells and the rows used."""
    cells_per_row = SHEET_WIDTH // CELL_SIZE
    placed = {}
    cell_x = cell_y = row_height = 0
    for name, image in items.items():
        wide, high = cells(image.width), cells(image.height)
        if cell_x + wide > cells_per_row:
            cell_x = 0
            cell_y += row_height
            row_height = 0
        placed[name] = (cell_x, cell_y)
        cell_x += wide
        row_height = max(row_height, high)
    return placed, cell_y + row_height


def write_module(
    path: Path,
    sheet_name: str,
    sheet_height: int,
    items: dict[str, Image.Image],
    placed: dict[str, tuple[int, int]],
) -> None:
    cells_per_row = SHEET_WIDTH // CELL_SIZE
    lines = [
        '"""Generated by tools/equipment.py, do not edit."""',
        "",
        "",
        "class Item:",
        f'    SHEET = "{sheet_name}"',
        f"    SHEET_WIDTH = {SHEET_WIDTH}",
        f"    SHEET_HEIGHT = {sheet_height}",
        "",
        "    def __init__(self, width, height, frame):",
        "        self.FRAME_WIDTH = width",
        "        self.FRAME_HEIGHT = height",
        '        self.ACTIONS = {"idle": (frame,)}',
        "",
        "",
    ]
    for name, image in items.items():
        cell_x, cell_y = placed[name]
        frame = cell_x + cell_y * cells_per_row
        lines.append(f"{name} = Item({image.width}, {image.height}, {frame})")
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines) + "\n")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "source", nargs="?", type=Path, default=Path("raw_assets/equipment")
    )
    args = parser.parse_args()

    paths = sorted(args.source.glob("*.png"))
    if not paths:
        parser.error(f"no PNGs found in {args.source}")

    items = {}
    for path in paths:
        if not path.stem.isidentifier():
            parser.error(f"{path.name}: the name must work as a Python class name")
        image = Image.open(path).convert("RGBA")
        if image.width > SHEET_WIDTH:
            parser.error(f"{path.name}: wider than the {SHEET_WIDTH} pixel sheet")
        items[path.stem] = image

    placed, rows = place_items(items)
    sheet = Image.new("RGBA", (SHEET_WIDTH, rows * CELL_SIZE))
    for name, image in items.items():
        cell_x, cell_y = placed[name]
        sheet.paste(image, (cell_x * CELL_SIZE, cell_y * CELL_SIZE))

    name = args.source.name
    sheet_name = f"{name}.16bpp"
    sheet_path = Path("assets") / sheet_name
    module_path = Path("src") / f"{name}.py"
    write_pixels(sheet_path, sheet)
    write_module(module_path, sheet_name, sheet.height, items, placed)
    print(f"{len(items)} items: wrote {sheet_path} and {module_path}")


if __name__ == "__main__":
    main()
