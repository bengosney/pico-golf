"""Build a PicoSystem sprite sheet and frame index module from a folder of PNGs."""

import argparse
import re
import struct
from pathlib import Path

from PIL import Image

SHEET_WIDTH = 128
CELL_SIZE = 8  # sprite() counts in 8x8 cells
ALPHA_THRESHOLD = 128


def action_and_frame(path: Path, prefix: str) -> tuple[str, int]:
    match = re.fullmatch(r"(.*?)(\d*)", path.stem.removeprefix(prefix))
    assert match
    return match[1], int(match[2] or 0)


def scale_frames(
    images: list[Image.Image], width: int, height: int
) -> list[Image.Image]:
    """Scale every image by the same amount, keeping their feet on the bottom edge."""
    boxes = [image.getchannel("A").getbbox() or (0, 0, 1, 1) for image in images]
    left = min(box[0] for box in boxes)
    top = min(box[1] for box in boxes)
    right = max(box[2] for box in boxes)
    bottom = max(box[3] for box in boxes)

    scale = min(width / (right - left), height / (bottom - top))
    size = (round((right - left) * scale), round((bottom - top) * scale))
    position = ((width - size[0]) // 2, height - size[1])

    frames = []
    for image in images:
        small = image.crop((left, top, right, bottom)).resize(
            size, Image.Resampling.BOX
        )
        frame = Image.new("RGBA", (width, height))
        frame.paste(small, position)
        frames.append(frame)
    return frames


def encode_pixel(red: int, green: int, blue: int, alpha: int) -> int:
    """Pack a pixel as the firmware's 16bit colour, with hard edged transparency."""
    if alpha < ALPHA_THRESHOLD:
        return 0
    return (green >> 4) << 12 | (blue >> 4) << 8 | 0xF << 4 | red >> 4


def write_pixels(path: Path, sheet: Image.Image) -> None:
    data = sheet.tobytes()
    pixels = [encode_pixel(*data[i : i + 4]) for i in range(0, len(data), 4)]
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(struct.pack(f"<{len(pixels)}H", *pixels))


def write_sheet(path: Path, frames: list[Image.Image], width: int, height: int) -> int:
    columns = SHEET_WIDTH // width
    rows = -(-len(frames) // columns)
    sheet = Image.new("RGBA", (SHEET_WIDTH, rows * height))
    for number, frame in enumerate(frames):
        sheet.paste(frame, (number % columns * width, number // columns * height))

    write_pixels(path, sheet)
    return sheet.height


def write_module(
    path: Path,
    sheet_name: str,
    sheet_height: int,
    width: int,
    height: int,
    actions: dict[str, list[int]],
) -> None:
    columns = SHEET_WIDTH // width
    cells_wide = width // CELL_SIZE
    cells_high = height // CELL_SIZE

    def sprite_index(frame: int) -> int:
        cell_x = frame % columns * cells_wide
        cell_y = frame // columns * cells_high
        return cell_x + cell_y * SHEET_WIDTH // CELL_SIZE

    lines = [
        '"""Generated by tools/character.py, do not edit."""',
        "",
        f'SHEET = "{sheet_name}"',
        f"SHEET_WIDTH = {SHEET_WIDTH}",
        f"SHEET_HEIGHT = {sheet_height}",
        f"FRAME_WIDTH = {width}",
        f"FRAME_HEIGHT = {height}",
        f"CELLS_WIDE = {cells_wide}",
        f"CELLS_HIGH = {cells_high}",
        "",
        "ACTIONS = {",
    ]
    for action, frames in sorted(actions.items()):
        indexes = ", ".join(str(sprite_index(frame)) for frame in frames)
        trailing = "," if len(frames) == 1 else ""
        lines.append(f'    "{action}": ({indexes}{trailing}),')
    lines.append("}")

    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines) + "\n")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "source", nargs="?", type=Path, default=Path("raw_assets/adventurer")
    )
    parser.add_argument("--frame-width", type=int, default=16)
    parser.add_argument("--frame-height", type=int, default=24)
    args = parser.parse_args()

    width, height = args.frame_width, args.frame_height
    if width % CELL_SIZE or height % CELL_SIZE:
        parser.error(f"frame size must be a multiple of {CELL_SIZE}")

    name = args.source.name
    prefix = f"{name}_"
    paths = sorted(
        args.source.glob("*.png"), key=lambda path: action_and_frame(path, prefix)
    )
    if not paths:
        parser.error(f"no PNGs found in {args.source}")

    actions: dict[str, list[int]] = {}
    for number, path in enumerate(paths):
        action, _ = action_and_frame(path, prefix)
        actions.setdefault(action, []).append(number)

    images = [Image.open(path).convert("RGBA") for path in paths]
    frames = scale_frames(images, width, height)

    sheet_name = f"{name}.16bpp"
    sheet_path = Path("assets") / sheet_name
    module_path = Path("src") / f"{name}.py"
    sheet_height = write_sheet(sheet_path, frames, width, height)
    write_module(module_path, sheet_name, sheet_height, width, height, actions)
    print(f"{len(frames)} frames: wrote {sheet_path} and {module_path}")


if __name__ == "__main__":
    main()
